INSERT INTO product_categories (category_name, is_active)
SELECT DISTINCT category, TRUE FROM menu_products
ON CONFLICT (category_name) DO UPDATE SET is_active = TRUE;

-- 2. Inventory items, each with a created entry in stock history
WITH added AS (
  INSERT INTO inventory (ingredient_category, item_name, unit_of_measure, quantity, low_stock_threshold, is_whole_unit)
  SELECT m.category, m.item_name, 'mL', 0, 500, FALSE
  FROM menu_items m
  WHERE NOT EXISTS (SELECT 1 FROM inventory i WHERE LOWER(i.item_name) = LOWER(m.item_name) AND i.is_archived = FALSE)
  RETURNING inventory_id, item_name, ingredient_category, unit_of_measure, quantity
)
INSERT INTO inventory_log (inventory_id, item_name, ingredient_category, unit_of_measure, change_type, quantity_before, quantity_after, quantity_delta, admin_id, source_app, note)
SELECT inventory_id, item_name, ingredient_category, unit_of_measure, 'created', 0, quantity, quantity,
  (SELECT admin_id FROM admin_users WHERE LOWER(role) = 'admin' AND is_active ORDER BY admin_id LIMIT 1), 'admin', 'Product list 2026'
FROM added;

-- 3. Drinks: anything not on the list is archived
UPDATE products p
SET is_archived = TRUE, archived_at = CURRENT_TIMESTAMP, updated_at = CURRENT_TIMESTAMP
WHERE p.is_archived = FALSE
  AND NOT EXISTS (SELECT 1 FROM menu_products m WHERE m.product_name = p.product_name);

UPDATE products p
SET product_category = m.category, product_type = 'recipe', station = 'bar', updated_at = CURRENT_TIMESTAMP
FROM menu_products m
WHERE p.product_name = m.product_name AND p.is_archived = FALSE;

INSERT INTO products (product_name, product_category, product_type, station, price)
SELECT m.product_name, m.category, 'recipe', 'bar', (SELECT MIN(v.price) FROM menu_variants v WHERE v.product_name = m.product_name)
FROM menu_products m
WHERE NOT EXISTS (SELECT 1 FROM products p WHERE p.product_name = m.product_name AND p.is_archived = FALSE);

-- 4. Sizes: add, price, bring back, and archive the ones not on the list
INSERT INTO product_variants (product_id, size_label, temperature, price)
SELECT p.product_id, v.size_label, v.temperature, v.price
FROM menu_variants v
JOIN products p ON p.product_name = v.product_name AND p.is_archived = FALSE
WHERE NOT EXISTS (
  SELECT 1 FROM product_variants pv
  WHERE pv.product_id = p.product_id AND LOWER(TRIM(pv.size_label)) = LOWER(v.size_label) AND pv.temperature IS NOT DISTINCT FROM v.temperature
);

UPDATE product_variants pv
SET price = v.price, is_archived = FALSE, archived_at = NULL, archived_by = NULL, updated_at = CURRENT_TIMESTAMP
FROM menu_variants v
JOIN products p ON p.product_name = v.product_name AND p.is_archived = FALSE
WHERE pv.product_id = p.product_id AND LOWER(TRIM(pv.size_label)) = LOWER(v.size_label) AND pv.temperature IS NOT DISTINCT FROM v.temperature;

UPDATE product_variants pv
SET is_archived = TRUE, archived_at = CURRENT_TIMESTAMP, updated_at = CURRENT_TIMESTAMP
FROM products p
WHERE pv.product_id = p.product_id AND pv.is_archived = FALSE
  AND (p.is_archived OR NOT EXISTS (
    SELECT 1 FROM menu_variants v
    WHERE v.product_name = p.product_name AND LOWER(v.size_label) = LOWER(TRIM(pv.size_label)) AND v.temperature IS NOT DISTINCT FROM pv.temperature
  ));

-- 5. Recipes: replaced with the sheet's
DELETE FROM variant_ingredients vi
USING product_variants pv, products p, menu_products m
WHERE vi.product_variant_id = pv.product_variant_id AND pv.product_id = p.product_id
  AND p.product_name = m.product_name AND p.is_archived = FALSE;

DELETE FROM product_ingredients pi
USING products p, menu_products m
WHERE pi.product_id = p.product_id AND p.product_name = m.product_name AND p.is_archived = FALSE;

INSERT INTO variant_ingredients (product_variant_id, inventory_id, required_quantity)
SELECT pv.product_variant_id, inv.inventory_id, r.qty
FROM menu_recipes r
JOIN products p ON p.product_name = r.product_name AND p.is_archived = FALSE
JOIN product_variants pv ON pv.product_id = p.product_id AND pv.is_archived = FALSE
  AND LOWER(TRIM(pv.size_label)) = LOWER(r.size_label) AND pv.temperature = r.temperature
JOIN LATERAL (
  SELECT i.inventory_id FROM inventory i
  WHERE LOWER(i.item_name) = LOWER(r.item_name) AND i.is_archived = FALSE
  ORDER BY i.inventory_id LIMIT 1
) inv ON TRUE;

